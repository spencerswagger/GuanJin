package main

import (
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"math/big"
	"os"
	"path/filepath"

	"github.com/golang-jwt/jwt/v5"
	"github.com/tjfoc/gmsm/sm2"

	"github.com/spencerswagger/GuanJin/internal/crypto"
)

var fixedPrivateD = mustHex("6f3a9c1e5b7d2048a1c6ef930d4b5782a0e1d3c5f708192a4b6d8e0f1a2c3d4e")

func mustHex(s string) *big.Int {
	raw, err := hex.DecodeString(s)
	if err != nil {
		panic(err)
	}
	return new(big.Int).SetBytes(raw)
}

type jwkOut struct {
	Kty string `json:"kty"`
	Use string `json:"use"`
	Kid string `json:"kid"`
	Alg string `json:"alg"`
	Crv string `json:"crv"`
	X   string `json:"x"`
	Y   string `json:"y"`
}

type vectorOut struct {
	Kid          string                 `json:"kid"`
	Alg          string                 `json:"alg"`
	Jwks         map[string]interface{} `json:"jwks"`
	PrivateKeyD  string                 `json:"private_key_d"`
	Token        string                 `json:"token"`
	Claims       map[string]interface{} `json:"claims"`
	Notes        string                 `json:"notes"`
}

func main() {
	out := flag.String("out", "sdk/guanjin-core/src/test/resources/jwt_vector.json", "output path")
	flag.Parse()

	curve := sm2.P256Sm2()
	x, y := curve.ScalarBaseMult(fixedPrivateD.Bytes())
	priv := &sm2.PrivateKey{
		PublicKey: sm2.PublicKey{Curve: curve, X: x, Y: y},
		D:         fixedPrivateD,
	}

	kid := "gw:testkey-0001"
	claims := jwt.MapClaims{
		"iss":   "guanjin-gateway",
		"sub":   "u_12345",
		"aud":   "order-service",
		"cid":   "order-portal",
		"uname": "zhangsan",
		"roles": []string{"order_admin", "auditor"},
		"acr":   "AAL2",
		"amr":   []string{"pwd", "otp"},
		"iat":   1730000000,
		"exp":   4102444800,
		"jti":   "2f8c1b90-2a3d-4e5f-8091-a2b3c4d5e6f7",
	}

	token := jwt.NewWithClaims(crypto.SigningMethodSM3WithSM2, claims)
	token.Header["kid"] = kid
	token.Header["typ"] = "JWT"
	signed, err := token.SignedString(priv)
	if err != nil {
		fail(err)
	}

	jwk := crypto.NewJWK(kid, crypto.AlgoSM2, &priv.PublicKey)
	jwks := map[string]interface{}{"keys": []jwkOut{{
		Kty: jwk.Kty, Use: jwk.Use, Kid: jwk.Kid, Alg: jwk.Alg, Crv: jwk.Crv, X: jwk.X, Y: jwk.Y,
	}}}

	vec := vectorOut{
		Kid:         kid,
		Alg:         crypto.AlgoSM3WithSM2,
		Jwks:        jwks,
		PrivateKeyD: base64.RawURLEncoding.EncodeToString(fixedPrivateD.FillBytes(make([]byte, 32))),
		Token:       signed,
		Claims:      claims,
		Notes:       "Generated by cmd/guanjsign using internal/crypto SigningMethodSM3WithSM2 (SM3(signingString) then raw SM2 sign over the 32-byte digest, no ZA).",
	}

	blob, err := json.MarshalIndent(vec, "", "  ")
	if err != nil {
		fail(err)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, append(blob, '\n'), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s\ntoken=%s\n", *out, signed)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
